-- PostgreSQL school database schema and example queries.

CREATE TABLE students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE courses (
    course_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(20) NOT NULL UNIQUE,
    course_name VARCHAR(100) NOT NULL
);

CREATE TABLE enrolments (
    enrolment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students (student_id),
    course_id INTEGER NOT NULL REFERENCES courses (course_id),
    enrolment_date DATE NOT NULL,
    grade NUMERIC(5, 2) CHECK (grade IS NULL OR (grade >= 0 AND grade <= 100)),
    CONSTRAINT unique_student_course UNIQUE (student_id, course_id)
);

CREATE INDEX idx_students_name ON students (name);

